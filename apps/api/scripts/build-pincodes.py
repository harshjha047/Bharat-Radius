#!/usr/bin/env python3
"""Rebuild apps/api/src/pincodes/data.ts from the All India Pincode Directory CSV.

  python3 apps/api/scripts/build-pincodes.py pincode.csv apps/api/src/pincodes/data.ts

CSV columns: CircleName,RegionName,DivisionName,OfficeName,Pincode,OfficeType,Delivery,District,StateName,...
(data.gov.in "All India Pincode Directory", GODL-India). A PIN served by several districts keeps the one
with the most post offices.
"""
import csv,collections,re,sys,json
src,out=sys.argv[1],sys.argv[2]
GST={'Jammu and Kashmir':'01','Himachal Pradesh':'02','Punjab':'03','Chandigarh':'04','Uttarakhand':'05','Haryana':'06','Delhi':'07','Rajasthan':'08','Uttar Pradesh':'09','Bihar':'10','Sikkim':'11','Arunachal Pradesh':'12','Nagaland':'13','Manipur':'14','Mizoram':'15','Tripura':'16','Meghalaya':'17','Assam':'18','West Bengal':'19','Jharkhand':'20','Odisha':'21','Chhattisgarh':'22','Madhya Pradesh':'23','Gujarat':'24','Dadra and Nagar Haveli and Daman and Diu':'26','Maharashtra':'27','Karnataka':'29','Goa':'30','Lakshadweep':'31','Kerala':'32','Tamil Nadu':'33','Puducherry':'34','Andaman and Nicobar Islands':'35','Telangana':'36','Andhra Pradesh':'37','Ladakh':'38'}
byup={k.upper():k for k in GST}
SMALL={'and','of','the'}
def title(s):
    s=re.sub(r'\s+',' ',s.strip())
    w=[x if i and x in SMALL else re.sub(r"(^|[-(.])([a-z])", lambda m:m.group(1)+m.group(2).upper(), x) for i,x in enumerate(s.lower().split(' '))]
    return ' '.join(w)
pins=collections.defaultdict(collections.Counter)
for r in csv.DictReader(open(src,encoding='utf-8',errors='replace')):
    st=re.sub(r'^THE ','',r['StateName'].strip().upper())
    pins[r['Pincode'].strip()][(title(r['District']),byup[st])]+=1
states=sorted(GST, key=lambda s:GST[s])
dists=sorted({d for c in pins.values() for (d,_) in c})
di={d:i for i,d in enumerate(dists)}; si={s:i for i,s in enumerate(states)}
rows=[]
for p in sorted(pins):
    (d,s),_=pins[p].most_common(1)[0]
    rows.append(f"{p}{di[d]:x}.{si[s]:x}")
with open(out,'w') as f:
    f.write("// Generated by apps/api/scripts/build-pincodes.py from the All India Pincode Directory\n")
    f.write("// (Department of Posts, data.gov.in, GODL-India). Do not edit by hand.\n")
    f.write("// PACKED: 6-digit PIN + district index (hex) + '.' + state index (hex), ';'-separated, sorted by PIN.\n\n")
    f.write(f"export const STATES: readonly (readonly [name: string, gstCode: string])[] = {json.dumps([[s,GST[s]] for s in states])};\n\n")
    f.write(f"export const DISTRICTS: readonly string[] = {json.dumps(dists, ensure_ascii=False)};\n\n")
    f.write(f"export const PACKED = '{';'.join(rows)}';\n")
print(len(rows),'pins',len(dists),'districts')
